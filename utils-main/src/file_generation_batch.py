"""Answer generation: batched Qwen3-0.6B inference over retrieved sources.

Prompts are built per question, sorted by length and generated by batches
(left padding), with a 1000-token context budget and 100 new tokens max.
"""

import os
import torch
from functools import lru_cache
from pathlib import Path
from tqdm import tqdm
import pydantic
from .file_indexer import load_index
from .file_searcher import search_one
from .models import UnansweredQuestion
from .utils import valid_positive_int, valid_query
from .models import MinimalSource, MinimalAnswer
from .models import StudentSearchResults, StudentSearchResultsAndAnswer
from transformers import AutoModelForCausalLM
from transformers import AutoTokenizer
from transformers import PreTrainedModel
from transformers import PreTrainedTokenizerBase


MODEL_NAME = "Qwen/Qwen3-0.6B"
BATCH_SIZE = 8
NUM_THREADS = 20
MAX_CONTEXT_TOKENS = 2000
MAX_NEW_TOKENS = 100
NO_INFO = "I could not find relevant information."


def env_int(name: str, default: int) -> int:
    """Read a positive integer from an environment variable.

    Args:
        name: Name of the environment variable.
        default: Value used if the variable is missing or invalid.

    Returns:
        The integer value, or ``default``.
    """

    try:
        value = int(os.environ.get(name, default))
    except ValueError:
        return default
    return value if value > 0 else default


BATCH_SIZE = env_int("BATCH_SIZE", 8)
NUM_THREADS = env_int("NUM_THREADS", 8)  # 8 = P-cores of the i7-14700


def load_model() -> tuple[PreTrainedTokenizerBase, PreTrainedModel]:
    """Load the Qwen tokenizer and model once, ready for inference.

    Returns:
        The tokenizer (left padding, needed for batches) and the model
        (in evaluation mode).
    """

    # to be powerful on pc if there are a GPU.
    device = "mps" if torch.backends.mps.is_available() else "cpu"
    if device == "cpu":
        torch.set_num_threads(NUM_THREADS)
    # left padding: pad tokens must be BEFORE the prompt for generation
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME, padding_side="left")
    model = AutoModelForCausalLM.from_pretrained(MODEL_NAME,
                                                 torch_dtype=torch.float32)
    model.to(device)  # type: ignore[arg-type]
    model.eval()
    return (tokenizer, model)


@lru_cache(maxsize=None)
def read_file(file_path: str) -> str | None:
    """Read a whole file once; later calls hit the in-memory cache.

    Args:
        file_path: Path of the file to read.

    Returns:
        The file content, or None if it is missing or not UTF-8.
    """

    try:
        with open(file_path, "r", encoding="utf-8") as f:
            return f.read()
    except (OSError, UnicodeDecodeError):
        return None


def read_source_text(source: MinimalSource) -> str | None:
    """Read the text a MinimalSource points to, or None if unreadable.

    Args:
        source: File path and character range to extract.

    Returns:
        The extracted text, or None if the file is missing or invalid.
    """

    content = read_file(source.file_path)
    if content is None:
        return None
    return content[source.first_character_index:
                   source.last_character_index]


def build_context(sources: list[MinimalSource],
                  tokenizer: PreTrainedTokenizerBase,
                  max_content_tok: int) -> str:
    """
    Builds a context string by concatenating text from a list of sources,
    ensuring the total token count does not exceed the specified maximum.
    Args:
        sources (list[MinimalSource]): A list of source objects from which
            text will be read.
        tokenizer (PreTrainedTokenizerBase): A tokenizer instance used to
            calculate token counts.
        max_content_tok (int): The maximum number of tokens allowed in the
            resulting context string.
    Returns:
        str: A concatenated string of source texts, separated by "\n\n---\n\n",
            adhering to the token limit.
    """

    chunkychunk = []
    used_tok = 0

    for src in sources:
        text = read_source_text(src)
        if text is None:
            continue

        chunks = "[src i : file_path]\n" + text
        n = len(tokenizer(chunks)["input_ids"])

        if used_tok + n > max_content_tok:
            break
        chunkychunk.append(chunks)
        used_tok = used_tok + n

    return "\n\n---\n\n".join(chunkychunk)


def build_messages(question: str, context: str) -> list[dict[str, str]]:
    """
    Constructs a list of message dictionaries for a conversational AI model.
    Args:
        question (str): The user's question to be answered.
        context (str): The context or information provided to base
            the answer on.
    Returns:
        list[dict[str, str]]: A list of dictionaries representing the system
            and user messages.
        Each dictionary contains:
            - "role" (str): The role of the message sender, either "system"
                or "user".
            - "content" (str): The content of the message,
                including the system prompt or user input.
    """

    system_prompt = (
        "Answer ONLY based on the context provided. "
        "If the context does not contain the answer, "
        "say that you don't know. "
        "Give a short and precise answer in one or two sentences, "
        "without making up names of functions or options."
    )

    user = "Context:\n" + context + "\n\nQuestion: " + question

    return [{"role": "system", "content": system_prompt},
            {"role": "user", "content": user}]


def build_prompt(question: str, sources: list[MinimalSource],
                 tokenizer: PreTrainedTokenizerBase) -> str | None:
    """
    Builds the full chat prompt (as text) for one question.
    Args:
        question (str): The question to be answered.
        sources (list[MinimalSource]): The retrieved sources to use as context.
        tokenizer (PreTrainedTokenizerBase): Tokenizer used for the token
                                            budget and the chat template.
    Returns:
        str | None: The prompt, or None if no source could be read.
    """

    context = build_context(sources, tokenizer, MAX_CONTEXT_TOKENS)
    if not context:
        return None

    messages = build_messages(question, context)
    prompt = tokenizer.apply_chat_template(
        messages, enable_thinking=False,
        add_generation_prompt=True, tokenize=False)
    assert isinstance(prompt, str)  # tokenize=False always returns str
    return prompt


def generate_batch(prompts: list[str],
                   tokenizer: PreTrainedTokenizerBase,
                   model: PreTrainedModel) -> list[str]:
    """
    Generates one answer per prompt, all prompts being processed together.
    Args:
        prompts (list[str]): The prompts built by build_prompt.
        tokenizer (PreTrainedTokenizerBase): Tokenizer (left padding).
        model (PreTrainedModel): The model used for generation.
    Returns:
        list[str]: The answers, in the same order as the prompts.
    """

    # padding=True: prompts of different lengths must be padded to stack them
    # .to(model.device) to be powerful on pc if there are a GPU.
    entry = tokenizer(prompts, return_tensors="pt",
                      padding=True).to(model.device)
    with torch.inference_mode():
        output_ids = model.generate(  # type: ignore[operator]
            **entry, max_new_tokens=MAX_NEW_TOKENS, do_sample=False)

    # all rows share the same padded prompt length: keep only the new tokens
    generated_ids = output_ids[:, entry["input_ids"].shape[1]:]
    decoded = tokenizer.batch_decode(generated_ids, skip_special_tokens=True)
    return [text.strip() for text in decoded]


def answer(query: str, k: int) -> str | None:
    """
    Answers a given query by retrieving relevant sources, generating an answer,
    and returning the result in JSON format.
    Args:
        query (str): The question or query to be answered.
        k (int): The number of top relevant sources to retrieve.
    Returns:
        str | None: A JSON-formatted string containing the question, retrieved
        sources, and the generated answer, or None if the index is not found.
    Raises:
        FileNotFoundError: If the index file is missing and cannot be loaded.
    Dependencies:
        - Requires the presence of a pre-built index in the "data/processed"
            directory.
        - Requires a tokenizer and model for answer generation.
    Notes:
        - Ensure the 'index' command has been run to build the index before
            calling this function.
        - The function uses BM25 for retrieving relevant sources and a
            language model for generating answers.
    """

    if not valid_query(query) or not valid_positive_int(k, "k"):
        return None

    try:
        (bm25, chunks) = load_index(Path("data/processed"))
    except FileNotFoundError:
        print("Error: index not found. Run 'index' first.")
        return None

    question = UnansweredQuestion(question=query)
    result = search_one(question, k, bm25, chunks)  # MinimalSearchResults

    (tokenizer, model) = load_model()

    prompt = build_prompt(result.question, result.retrieved_sources, tokenizer)
    text = generate_batch([prompt], tokenizer, model)[0] if prompt else NO_INFO

    min_answer = MinimalAnswer(
        question_id=result.question_id,
        question=result.question,
        retrieved_sources=result.retrieved_sources,
        answer=text,
    )

    return min_answer.model_dump_json(indent=2)


def answer_dataset(student_search_results_path: str,
                   save_directory: str) -> None:
    """
    Processes a dataset of student search results, generates answers for each
    question (by batches), and saves the results to a specified directory.
    Args:
        student_search_results_path (str): The file path to the JSON file
            containing student search results.
        save_directory (str): The directory where the output file with
            answers will be saved.
    Returns:
        None
    Raises:
        FileNotFoundError: If the specified dataset file is not found.
        pydantic.ValidationError: If the dataset JSON is invalid.
    Workflow:
        1. Reads and validates the student search results JSON file.
        2. Loads the tokenizer and model for generating answers.
        3. Iterates through the search results by batches, generating
            the answers.
        4. Constructs a new dataset containing the original search results
            and the generated answers.
        5. Saves the new dataset as a JSON file in the specified directory.
    """

    try:
        path = Path(student_search_results_path)
        search_data = StudentSearchResults.model_validate_json(
            path.read_text())
    except FileNotFoundError:
        print(f"Error: dataset file not found: {path}")
        return None
    except pydantic.ValidationError as e:
        print(f"Error: invalid dataset JSON: {e}")
        return None

    (tokenizer, model) = load_model()
    items = search_data.search_results

    # 1. build every prompt (None when no source could be read)
    prompts = [build_prompt(it.question, it.retrieved_sources, tokenizer)
               for it in tqdm(items, desc="Building prompts")]

    # 2. keep (original index, prompt) for valid prompts, sorted by
    #    token length: similar lengths in a batch = less padding
    valid: list[tuple[int, str]] = [
        (i, p) for i, p in enumerate(prompts) if p is not None]
    valid.sort(key=lambda ip: len(tokenizer(ip[1])["input_ids"]))

    # 3. generate by batch, writing each answer back at its index
    texts: list[str] = [NO_INFO] * len(items)
    for start in tqdm(range(0, len(valid), BATCH_SIZE), desc="Answering"):
        batch = valid[start:start + BATCH_SIZE]
        outputs = generate_batch([p for _, p in batch], tokenizer, model)
        for (i, _), out in zip(batch, outputs):
            texts[i] = out

    # 4. rebuild the answers in the original dataset order
    answers = [
        MinimalAnswer(question_id=it.question_id, question=it.question,
                      retrieved_sources=it.retrieved_sources, answer=text)
        for it, text in zip(items, texts)
    ]

    result_answer = StudentSearchResultsAndAnswer(search_results=answers,
                                                  k=search_data.k)

    Path(save_directory).mkdir(parents=True, exist_ok=True)
    output_path = Path(save_directory) / path.name
    output_path.write_text(result_answer.model_dump_json(indent=2))
    print(f'Saved student_search_results_and_answer to {output_path}')
